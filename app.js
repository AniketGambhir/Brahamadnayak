/* =========================================
   GET LANGUAGE
========================================= */

function getLanguage() {

    const params = new URLSearchParams(
        window.location.search
    );

    const language = params.get("lang");

    if (
        language === "mr" ||
        language === "hi" ||
        language === "en"
    ) {
        return language;
    }

    return "en";
}


/* =========================================
   APPLY LANGUAGE
========================================= */

function applyLanguage(language) {

    const data =
        translations[language] || translations.en;

    const serviceData =
        serviceTranslations[language] ||
        serviceTranslations.en;

    const descriptionData =
        serviceDescriptions[language] ||
        serviceDescriptions.en;


    /* Normal text */

    document
        .querySelectorAll("[data-text]")
        .forEach(element => {

            const key =
                element.getAttribute("data-text");

            if (data[key]) {
                element.textContent = data[key];
            }

        });


    /* Service names */

    document
        .querySelectorAll("[data-service]")
        .forEach(element => {

            const key =
                element.getAttribute("data-service");

            if (serviceData[key]) {
                element.textContent =
                    serviceData[key];
            }

        });


    /* Service descriptions */

    document
        .querySelectorAll("[data-service-desc]")
        .forEach(element => {

            const key =
                element.getAttribute("data-service-desc");

            if (descriptionData[key]) {
                element.textContent =
                    descriptionData[key];
            }

        });


    /* Form placeholders */

    const nameInput =
        document.getElementById("customerName");

    const addressInput =
        document.getElementById("customerAddress");

    const mobileInput =
        document.getElementById("customerMobile");

    const problemInput =
        document.getElementById("customerProblem");


    if (language === "mr") {

        if (nameInput)
            nameInput.placeholder =
                "आपले नाव लिहा";

        if (addressInput)
            addressInput.placeholder =
                "आपला घराचा पत्ता लिहा";

        if (mobileInput)
            mobileInput.placeholder =
                "10 अंकी मोबाईल नंबर लिहा";

        if (problemInput)
            problemInput.placeholder =
                "आपली समस्या लिहा";

    }


    else if (language === "hi") {

        if (nameInput)
            nameInput.placeholder =
                "अपना नाम लिखें";

        if (addressInput)
            addressInput.placeholder =
                "अपना घर का पता लिखें";

        if (mobileInput)
            mobileInput.placeholder =
                "10 अंकों का मोबाइल नंबर लिखें";

        if (problemInput)
            problemInput.placeholder =
                "अपनी समस्या लिखें";

    }


    else {

        if (nameInput)
            nameInput.placeholder =
                "Enter your name";

        if (addressInput)
            addressInput.placeholder =
                "Enter your home address";

        if (mobileInput)
            mobileInput.placeholder =
                "Enter 10-digit mobile number";

        if (problemInput)
            problemInput.placeholder =
                "Describe your problem";

    }

}


/* =========================================
   WHATSAPP BOOKING
========================================= */

function setupBooking() {

    const form =
        document.getElementById("bookingForm");

    if (!form) {
        return;
    }


    form.addEventListener("submit", function(event) {

        event.preventDefault();


        const name =
            document
                .getElementById("customerName")
                .value.trim();


        const address =
            document
                .getElementById("customerAddress")
                .value.trim();


        const mobile =
            document
                .getElementById("customerMobile")
                .value.trim();


        const service =
            document
                .getElementById("serviceSelect")
                .value;


        const problem =
            document
                .getElementById("customerProblem")
                .value.trim();


        /* Mobile validation */

        if (!/^[0-9]{10}$/.test(mobile)) {

            alert(
                "Please enter a valid 10-digit mobile number."
            );

            return;
        }


        if (!service) {

            alert(
                "Please select a service."
            );

            return;
        }


        /* WhatsApp number */

        const businessNumber =
            "919075439504";


        const language =
            getLanguage();


        let message = "";


        if (language === "mr") {

            message =
                `नमस्कार ब्रह्मांडनायक,

मला घरगुती सेवा बुक करायची आहे.

नाव: ${name}

पत्ता: ${address}

मोबाईल: ${mobile}

सेवा: ${service}

समस्या / काम:
${problem}

कृपया माझ्याशी संपर्क करा.

धन्यवाद.`;

        }


        else if (language === "hi") {

            message =
                `नमस्ते ब्रह्मांडनायक,

मुझे होम सर्विस बुक करनी है।

नाम: ${name}

पता: ${address}

मोबाइल: ${mobile}

सेवा: ${service}

समस्या / काम:
${problem}

कृपया मुझसे संपर्क करें।

धन्यवाद।`;

        }


        else {

            message =
                `Hello Brahamadnayak,

I would like to book a home service.

Name: ${name}

Address: ${address}

Mobile: ${mobile}

Service: ${service}

Problem / Task:
${problem}

Please contact me.

Thank you.`;

        }


        const whatsappURL =
            `https://wa.me/${businessNumber}?text=` +
            encodeURIComponent(message);


        window.open(
            whatsappURL,
            "_blank"
        );

    });

}


/* =========================================
   CURSOR GLOW
========================================= */

function setupCursorGlow() {

    const glow =
        document.querySelector(".cursor-glow");

    if (!glow) {
        return;
    }


    document.addEventListener(
        "mousemove",
        function(event) {

            glow.style.left =
                event.clientX + "px";

            glow.style.top =
                event.clientY + "px";

        }
    );

}


/* =========================================
   COPYRIGHT YEAR
========================================= */

function setupYear() {

    const year =
        document.getElementById("year");

    if (year) {

        year.textContent =
            new Date().getFullYear();

    }

}


/* =========================================
   START WEBSITE
========================================= */

document.addEventListener(
    "DOMContentLoaded",
    function() {

        const language =
            getLanguage();

        applyLanguage(language);

        setupBooking();

        setupCursorGlow();

        setupYear();

    }
);
